library(Benchmarking)
data(charnes1981)
X <- as.matrix(charnes1981[, c("x1", "x2", "x3", "x4", "x5")])
Y <- as.matrix(charnes1981[, c("y1", "y2", "y3")])
fit <- dea(X, Y, RTS="vrs", ORIENTATION="out", SLACK=TRUE)
write.csv(data.frame(DMU=seq_len(nrow(X)), efficiency=fit$eff), "benchmarking_charnes_eff.csv", row.names=FALSE)
write.csv(fit$lambda, "benchmarking_charnes_lambda.csv", row.names=FALSE)
write.csv(fit$sx, "benchmarking_charnes_sx.csv", row.names=FALSE)
write.csv(fit$sy, "benchmarking_charnes_sy.csv", row.names=FALSE)
write.csv(X, "benchmarking_charnes_X.csv", row.names=FALSE)
write.csv(Y, "benchmarking_charnes_Y.csv", row.names=FALSE)
cat("Benchmarking package version:", as.character(packageVersion("Benchmarking")), "\n")
